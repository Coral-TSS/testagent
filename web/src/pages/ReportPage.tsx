import { ListSection, ListTable } from "../components/ListView";
import { useQuery } from "@tanstack/react-query";
import { Alert, Button, Card, Col, Descriptions, Row, Space, Statistic, Tag, Typography } from "antd";
import dayjs from "dayjs";
import { Link, useNavigate, useParams } from "react-router-dom";

import { api } from "../api/client";
import { useApiMutation } from "../api/hooks";
import type { Report, ReportContent, SuspectedCause } from "../api/types";
import { CAUSE_TAG, CauseTag } from "../components/FailureSummary";
import { CAUSE_LABEL, DefectStatusTag, ROLE_LABEL, SEVERITY, SeverityTag } from "../components/DefectTags";
import { ExecutionStatusTag } from "../components/StatusTags";
import { ByRole, RequirementStatsTable, fmtScore } from "../components/StatsTables";
import { SCOPE_LABEL, passRateNote, passRateText, pct } from "./ReportsPage";
import { CorrectionButton } from "../components/CorrectionButton";

type PersonRow = ReportContent["by_person"][number];
type DefectRow = ReportContent["defects"][number];
type FailureRow = ReportContent["failures"][number];

/** P11 report detail: read-only snapshot (immutable once generated; regenerate for fresh data) */
export function ReportPage() {
  const { reportId = "" } = useParams();
  const navigate = useNavigate();
  const q = useQuery({ queryKey: ["report", reportId], queryFn: () => api<Report>(`/reports/${reportId}`) });
  const r = q.data;
  const regenerate = useApiMutation(
    () =>
      r!.scope_type === "version"
        ? api<Report>(`/versions/${r!.scope_id}/report`, { method: "POST" })
        : api<Report>(`/runs/${r!.scope_id}/report`, { method: "POST" }),
    { success: "New report generated (the original report is kept unchanged)", invalidate: [["reports"]], onSuccess: (n) => navigate(`/reports/${n.id}`) },
  );
  if (!r) return <Card loading={q.isLoading}>{q.isError && "Report not found"}</Card>;
  const c = r.content;
  const s = c.summary;
  const weights = Object.keys(SEVERITY)
    .filter((k) => k in c.weights_used)
    .map((k) => `${SEVERITY[k][0]} ${c.weights_used[k]}`)
    .join(" · ");
  return (
    <>
      <Card
        style={{ marginBottom: 16 }}
        title={
          <>
            {SCOPE_LABEL[r.scope_type]}: {c.scope.type === "version" ? `Version ${c.scope.version_name}` : `${c.scope.task_name} · version ${c.scope.version_name}`}
          </>
        }
        extra={
          <Space>
            <CorrectionButton targetType="report" targetId={r.id} placeholder="e.g. A failure was assigned to the wrong requirement; the summary called an environment problem a development problem" />
            <Button loading={regenerate.isPending} onClick={() => regenerate.mutate()}>
              Regenerate
            </Button>
          </Space>
        }
      >
        <Alert type="info" showIcon style={{ marginBottom: 12 }} message="A report is a snapshot of the moment it was generated and cannot be changed; regenerating creates a new report." />
        <Row gutter={16} style={{ marginBottom: 12 }}>
          <Col span={4}><Statistic title="Case" value={s.total} /></Col>
          <Col span={4}><Statistic title="Passed" value={s.passed} /></Col>
          <Col span={4}><Statistic title="Failed / error" value={`${s.failed} / ${s.error}`} /></Col>
          <Col span={4}><Statistic title="Blocked / skipped" value={`${s.blocked} / ${s.skipped}`} /></Col>
          <Col span={4}><Statistic title="Not run" value={s.not_executed} /></Col>
          <Col span={4}><Statistic title="Pass rate" value={passRateText(s)} /></Col>
        </Row>
        {(s.skipped > 0 || s.blocked > 0 || s.not_executed > 0) && (
          <Alert type="warning" showIcon style={{ marginBottom: 12 }} data-testid="pass-rate-note" title={passRateNote(s)} />
        )}
        {s.by_cause && Object.values(s.by_cause).some((n) => n > 0) && (
          <Space wrap style={{ marginBottom: 12 }} data-testid="by-cause">
            <Typography.Text type="secondary">Failures by suspected cause:</Typography.Text>
            {(Object.entries(s.by_cause) as [SuspectedCause, number][])
              .filter(([, n]) => n > 0)
              .map(([cause, n]) => (
                <Tag key={cause} color={CAUSE_TAG[cause][1]}>
                  {CAUSE_TAG[cause][0]} {n}
                </Tag>
              ))}
            {(s.by_cause.platform || 0) + (s.by_cause.environment || 0) > 0 && (
              <Typography.Text type="secondary">Platform and environment failures are not defects of the system.</Typography.Text>
            )}
          </Space>
        )}
        <Descriptions size="small" column={3}>
          <Descriptions.Item label="Generated at">{dayjs(r.created_at).format("YYYY-MM-DD HH:mm:ss")}</Descriptions.Item>
          <Descriptions.Item label="Generated by">{r.created_by === "system" ? "System (automatically at run end)" : r.created_by}</Descriptions.Item>
          <Descriptions.Item label="Severity weights">{weights}</Descriptions.Item>
          {c.scope.task_run_id && (
            <Descriptions.Item label="Run">
              <Link to={`/runs/${c.scope.task_run_id}`}>View run</Link>
            </Descriptions.Item>
          )}
          <Descriptions.Item label="Version">
            <Link to={`/versions/${c.scope.version_id}`}>{c.scope.version_name}</Link>
          </Descriptions.Item>
          <Descriptions.Item label="Model snapshot">{c.snapshot_id ? <Tag color="purple">Linked</Tag> : "-"}</Descriptions.Item>
        </Descriptions>
      </Card>

      {(c.by_category?.length ?? 0) > 0 && (
        <Card style={{ marginBottom: 16 }} title="By case category: pass rate = passed ÷ executed (skipped, blocked and not run do not count)" data-testid="by-category">
          <ListTable
            pagination={false}
            label="Category results"
            size="small"
            rowKey="category"

            dataSource={c.by_category}
            columns={[
              { title: "category", dataIndex: "label" },
              { title: "Case", dataIndex: "total" },
              { title: "Executed", render: (_: unknown, r: NonNullable<ReportContent["by_category"]>[number]) => r.executed ?? r.passed + r.failed + r.error },
              { title: "Passed", dataIndex: "passed" },
              { title: "Failed / error", render: (_: unknown, r: NonNullable<ReportContent["by_category"]>[number]) => `${r.failed} / ${r.error}` },
              { title: "Skipped / blocked / not run", render: (_: unknown, r: NonNullable<ReportContent["by_category"]>[number]) => `${r.skipped} / ${r.blocked} / ${r.not_executed}` },
              { title: "Pass rate", dataIndex: "pass_rate", render: (v: number | null) => pct(v) },
            ]}
          />
        </Card>
      )}
      <Card style={{ marginBottom: 16 }} title="AI summary">
        {r.ai_summary ? (
          <>
            <Typography.Paragraph style={{ whiteSpace: "pre-wrap" }}>{r.ai_summary}</Typography.Paragraph>
            {r.agent_run_id && <Link to={`/agent/runs?run=${r.agent_run_id}`}>View agent trace</Link>}
          </>
        ) : (
          <Typography.Text type="secondary">No AI summary (no model configured or generation failed); the statistics below are not affected.</Typography.Text>
        )}
      </Card>

      <Card style={{ marginBottom: 16 }} title="By requirement: defect density (defects ÷ executed cases) and severity-weighted score">
        <RequirementStatsTable rows={c.by_requirement} paginate={false} />
      </Card>

      <Card style={{ marginBottom: 16 }} title="By person: attributed defects (rejected defects do not count)">
        <ListTable<PersonRow>
          pagination={false}
          label="Report people"
          size="small"
          rowKey="person_id"

          dataSource={c.by_person}
          locale={{ emptyText: "No people data" }}
          columns={[
            { title: "Person", dataIndex: "name", render: (v: string, p) => <Link to={`/defects?person_id=${p.person_id}`}>{v}</Link> },
            { title: "Attributed defects", dataIndex: "attributed_count", width: 90 },
            { title: "Weighted score", dataIndex: "attributed_score", width: 80, render: fmtScore },
            { title: "By role", dataIndex: "attributed_by_role", render: (v: PersonRow["attributed_by_role"]) => <ByRole value={v} /> },
            { title: "Related defects", dataIndex: "related_count", width: 90 },
            { title: "Main requirements", dataIndex: "top_requirements", render: (v: string[]) => v.map((x) => <Tag key={x}>{x}</Tag>) },
          ]}
        />
      </Card>

      <Card style={{ marginBottom: 16 }} title={`Failures and errors (${c.failures.length})`}>
        <ListTable<FailureRow>
          pagination={false}
          label="Failed executions"
          size="small"
          rowKey="execution_id"
          dataSource={c.failures}
          locale={{ emptyText: "No failed cases" }}
          columns={[
            { title: "Case", dataIndex: "case", render: (v: FailureRow["case"]) => <Link to={`/cases/${v.id}`}>{v.code} {v.title}</Link> },
            { title: "Requirement", dataIndex: "requirement_codes", render: (v: string[]) => v.map((x) => <Tag key={x}>{x}</Tag>) },
            { title: "Result", dataIndex: "status", width: 80, render: (v: string) => <ExecutionStatusTag status={v} /> },
            { title: "Cause", key: "cause", width: 150, render: (_: unknown, f) => <CauseTag cause={f.suspected_cause} /> },
            { title: "Failed assertion / error", key: "why", render: (_: unknown, f) => f.headline || f.failed_assertion || f.error || "-" },
            { title: "Execution", dataIndex: "execution_id", width: 70, render: (v: string) => <Link to={`/executions/${v}`}>Detail</Link> },
            { title: "Defect", dataIndex: "defect_ids", width: 70, render: (v: string[]) => v.length || "-" },
          ]}
        />
      </Card>

      {(c.no_script?.length || 0) > 0 && (
        <Card style={{ marginBottom: 16 }} title={`Not executed: no automation script (${c.no_script!.length})`} data-testid="report-no-script">
          <Typography.Paragraph type="secondary">These cases are in an automated task but have no script yet; they were skipped and are not counted in the pass rate.</Typography.Paragraph>
          <ListSection label="Report cases without scripts" count={c.no_script!.length}>
          <Space wrap>
            {c.no_script!.map((n) => (
              <Link key={n.execution_id} to={`/cases/${n.case.id}`}>
                {n.case.code} {n.case.title}
              </Link>
            ))}
          </Space>
          </ListSection>
        </Card>
      )}

      <Card style={{ marginBottom: 16 }} title={`Defects (${c.defects.length})`}>
        <ListTable<DefectRow>
          pagination={false}
          label="Report defects"
          size="small"
          rowKey="id"
          dataSource={c.defects}
          locale={{ emptyText: "No defects" }}
          columns={[
            { title: "Code", dataIndex: "code", width: 90, render: (v: string, d) => <Link to={`/defects/${d.id}`}>{v}</Link> },
            { title: "Title", dataIndex: "title" },
            { title: "Severity", dataIndex: "severity", width: 80, render: (v: string) => <SeverityTag value={v} /> },
            { title: "Status (at generation)", dataIndex: "status", width: 110, render: (v: string) => <DefectStatusTag status={v} /> },
            { title: "Reason", dataIndex: "cause_category", width: 100, render: (v: string) => CAUSE_LABEL[v] || v },
            { title: "Requirement", dataIndex: "requirements", render: (v: string[]) => v.map((x) => <Tag key={x}>{x}</Tag>) },
            {
              title: "Attributed to",
              dataIndex: "responsible",
              render: (v: DefectRow["responsible"]) => v.map((p) => `${p.name} (${ROLE_LABEL[p.role] || p.role})`).join(", ") || "-",
            },
          ]}
        />
      </Card>

      <Card title="Code links (requirement → node / API → code location)">
        <ListSection label="Report code links" count={c.code_links.filter((l) => l.nodes.length || l.apis.length).length}>
        {c.code_links.every((l) => !l.nodes.length && !l.apis.length) ? (
          <Typography.Text type="secondary">No linked nodes or APIs</Typography.Text>
        ) : (
          c.code_links
            .filter((l) => l.nodes.length || l.apis.length)
            .map((l) => (
              <Descriptions key={l.requirement_code} size="small" column={1} title={l.requirement_code} style={{ marginBottom: 8 }}>
                {l.nodes.map((n) => (
                  <Descriptions.Item key={`n-${n.name}`} label="Node">
                    {n.name}
                    {n.code_ref ? ` · ${n.code_ref}` : ""}
                  </Descriptions.Item>
                ))}
                {l.apis.map((a) => (
                  <Descriptions.Item key={`a-${a.method}-${a.path}`} label="API">
                    {`${a.method} ${a.path}`}
                    {a.code_ref ? ` · ${a.code_ref}` : ""}
                  </Descriptions.Item>
                ))}
              </Descriptions>
            ))
        )}
        </ListSection>
      </Card>
    </>
  );
}
